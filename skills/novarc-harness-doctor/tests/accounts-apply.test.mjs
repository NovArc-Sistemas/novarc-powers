test('undo: restores byte-identical originals and removes what the run created', (t) => {
  for (const extra of [{}, { NOVARC_POWERS_NO_SYMLINK: '1' }]) {
    const h = buildHome();
    t.after(() => rmrf(h.root));
    const before = harness(h);
    const { apply } = planAndApply(h, 'claude-1', [...RESOLVE_ALL, '--resolve', 'claude-2:output-styles/=adopt-into-primary'], extra);
    assert.equal(apply.code, 0, apply.stdout);
    assert.notDeepEqual(harness(h), before);
    const refused = acc(h.home, ['undo', '--stamp', apply.json.stamp], extra);
    assert.equal(refused.code, 2);
    const dry = acc(h.home, ['undo', '--stamp', apply.json.stamp, '--dry-run'], extra);
    assert.equal(dry.code, 0);
    assert.equal(dry.json.dryRun, true);
    assert.notDeepEqual(harness(h), before, 'a dry run undid something');
    const undo = acc(h.home, ['undo', '--stamp', apply.json.stamp, '--yes'], extra);
    assert.equal(undo.code, 0, undo.stdout);
    assert.deepEqual(undo.json.conflicts, []);
    assert.ok(undo.json.restored > 0 && undo.json.removed > 0);
    assert.deepEqual(harness(h), before, 'the tree is not byte-identical after undo');
    assert.ok(!exists(path.join(h.sync, 'manifest.json')), 'the manifest of the undone run is gone');
    assertCanariesUntouched(assert, h);
    const again = acc(h.home, ['undo', '--stamp', apply.json.stamp, '--yes'], extra);
    assert.equal(again.code, 0);
    assert.match(again.json.note, /already undone/);
    assertClean(assert, h, undo.stdout + undo.stderr);
  }
});

test('undo: what changed since the run is left alone and reported', (t) => {
  const h = buildHome();
  t.after(() => rmrf(h.root));
  const { apply } = planAndApply(h, 'claude-1', RESOLVE_ALL);
  fs.appendFileSync(path.join(h.codexDir, 'AGENTS.md'), '\nEdited by hand after the run.\n');
  fs.rmSync(path.join(h.acc, 'keybindings.json')); // a link the user removed
  write(path.join(h.acc, 'keybindings.json'), '{"bindings": ["mine"]}\n');
  const undo = acc(h.home, ['undo', '--stamp', apply.json.stamp, '--yes']);
  assert.equal(undo.code, 1);
  assert.equal(undo.json.ok, false);
  const paths = undo.json.conflicts.map((c) => c.path);
  assert.ok(paths.includes('~/.codex/AGENTS.md'));
  assert.ok(paths.some((p) => p.endsWith('/acc-1/keybindings.json')));
  assert.ok(read(path.join(h.codexDir, 'AGENTS.md')).includes('Edited by hand after the run.'), 'an edited file was overwritten by undo');
  assert.equal(read(path.join(h.acc, 'keybindings.json')), '{"bindings": ["mine"]}\n');
  // Everything else was still undone.
  assert.equal(read(path.join(h.acc, 'CLAUDE.md')), '# Rules of the second account\n\nDifferent on purpose.\n');
  assert.ok(!read(path.join(h.codexDir, 'config.toml')).includes('novarc-harness-doctor'));
  assertClean(assert, h, undo.stdout + undo.stderr);
  // Bad stamps.
  assert.equal(acc(h.home, ['undo', '--stamp', '19990101-000000', '--yes']).code, 2);
  const none = acc(h.home, ['undo', '--yes']);
  assert.equal(none.code, 2);
  assert.deepEqual(none.json.stamps, [apply.json.stamp]);
  assert.equal(acc(h.home, ['undo', '--stamp', '../../x', '--yes']).code, 2);
});

