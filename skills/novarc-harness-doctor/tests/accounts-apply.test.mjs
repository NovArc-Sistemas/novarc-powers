test('where no link is possible at all, a file becomes a managed copy that is kept current', (t) => {
  const X = { NOVARC_POWERS_NO_SYMLINK: '2' }; // as when the two config dirs are on different volumes
  const h = buildHome({ codex: false, agents: false });
  t.after(() => rmrf(h.root));
  const before = harness(h);
  const { apply } = planAndApply(h, 'claude-1', ['--resolve', 'claude-2:CLAUDE.md=replace-with-primary'], X);
  assert.equal(apply.code, 0, apply.stdout);
  assert.equal(apply.json.done.find((d) => d.element === 'keybindings.json').kind, 'managed copy');
  const P = path.join(h.claude, 'keybindings.json');
  const S = path.join(h.acc, 'keybindings.json');
  assert.ok(!isLink(S) && fs.statSync(S).nlink === 1 && read(S) === read(P), 'a plain, identical copy');
  const rec = el(manifestOf(h), 'claude-2', 'keybindings.json');
  assert.deepEqual([rec.kind, rec.generator.type, rec.contentHash], ['generated', 'copy', sha(P)]);
  assert.ok(resolvesTo(path.join(h.acc, 'agents'), path.join(h.claude, 'agents')), 'folders can still be linked');
  const state = (name) => acc(h.home, ['diff'], X).json.accounts[1].sync.elements.find((e) => e.name === name);
  assert.deepEqual([state('keybindings.json').state, acc(h.home, ['diff'], X).json.accounts[1].sync.status], ['generated', 'ok']);
  assert.equal(acc(h.home, ['check', '--repair'], X).json.status, 'ok');
  // The primary changes: the copy is out of date, and the check brings it up to date.
  fs.writeFileSync(P, '{"bindings": ["changed in the primary"]}\n');
  assert.match(state('keybindings.json').note, /out of date/);
  assert.deepEqual(acc(h.home, ['plan', '--primary', 'claude-1'], X).json.actions.filter((a) => a.element === 'keybindings.json').map((a) => a.action), ['backup', 'link']);
  const fixed = acc(h.home, ['check', '--repair'], X).json;
  assert.equal(fixed.accounts[0].elements.find((e) => e.name === 'keybindings.json').repaired, true);
  assert.equal(read(S), read(P));
  // A new import of the primary arrives as a managed copy too.
  write(path.join(h.claude, 'LATER.md'), 'Imported later.\n');
  fs.appendFileSync(path.join(h.claude, 'CLAUDE.md'), '\n@LATER.md\n');
  acc(h.home, ['check', '--repair'], X);
  assert.equal(read(path.join(h.acc, 'LATER.md')), 'Imported later.\n');
  assert.equal(el(manifestOf(h), 'claude-2', 'LATER.md').generator.type, 'copy');
  assert.equal(read(path.join(h.acc, 'CLAUDE.md')), read(path.join(h.claude, 'CLAUDE.md')), 'the instruction file copy followed as well');
  // When the primary drops it again, the copy has content: it is left, and said once.
  fs.rmSync(path.join(h.claude, 'LATER.md'));
  fs.writeFileSync(path.join(h.claude, 'CLAUDE.md'), read(path.join(h.claude, 'CLAUDE.md')).replace('\n@LATER.md\n', ''));
  assert.match(acc(h.home, ['check', '--repair'], X).json.accounts[0].elements.find((e) => e.name === 'LATER.md').note, /left as it is/);
  assert.equal(acc(h.home, ['check', '--repair'], X).json.accounts[0].elements.find((e) => e.name === 'LATER.md'), undefined);
  fs.rmSync(path.join(h.acc, 'LATER.md'));
  // A copy edited by hand is never overwritten.
  fs.writeFileSync(S, '{"bindings": ["typed in the second account"]}\n');
  fs.writeFileSync(P, '{"bindings": ["changed again"]}\n');
  assert.equal(acc(h.home, ['check', '--repair'], X).json.accounts[0].elements.find((e) => e.name === 'keybindings.json').decide, true);
  assert.equal(read(S), '{"bindings": ["typed in the second account"]}\n');
  assert.equal(state('keybindings.json').state, 'divergent');
  // Undo of the original run: the untouched copies go, the edited one is reported and kept.
  fs.writeFileSync(P, '{"bindings": []}\n');
  const undo = acc(h.home, ['undo', '--stamp', apply.json.stamp, '--yes'], X);
  assert.deepEqual(undo.json.conflicts.map((c) => c.path.split('/').pop()), ['keybindings.json']);
  fs.rmSync(S);
  assert.deepEqual(harness(h), before);
});

test('plan --symlinks turns hardlinks into symbolic links, and undo brings the hardlinks back', (t) => {
  const h = buildHome({ codex: false, agents: false });
  t.after(() => rmrf(h.root));
  const first = planAndApply(h, 'claude-1', ['--resolve', 'claude-2:CLAUDE.md=replace-with-primary'], { NOVARC_POWERS_NO_SYMLINK: '1' });
  assert.equal(first.apply.code, 0, first.apply.stdout);
  const S = path.join(h.acc, 'CLAUDE.md');
  const P = path.join(h.claude, 'CLAUDE.md');
  assert.equal(el(manifestOf(h), 'claude-2', 'CLAUDE.md').kind, 'hardlink');
  // Without the flag a hardlink is simply "already linked".
  assert.equal(acc(h.home, ['plan', '--primary', 'claude-1']).json.summary.link, 0);
  const planFile = path.join(h.root, 'symlinks.json');
  const plan = acc(h.home, ['plan', '--primary', 'claude-1', '--symlinks', '--out', planFile]);
  assert.deepEqual(plan.json.options, { symlinks: true });
  const a = plan.json.actions.filter((x) => x.account === 'claude-2' && x.element === 'CLAUDE.md');
  assert.deepEqual(a.map((x) => x.action), ['backup', 'link']);
  assert.equal(a[1].replaces, 'a hardlink to the same file');
  assert.ok(plan.json.actions.every((x) => !(x.element === 'skills/' && x.action === 'link')), 'folders are not hardlinks; nothing to upgrade');
  const apply = acc(h.home, ['apply', '--plan', planFile, '--yes']);
  assert.equal(apply.code, 0, apply.stdout);
  assert.ok(resolvesTo(S, P));
  if (CAN_SYMLINK) {
    assert.ok(isLink(S), 'the hardlink did not become a symbolic link');
    assert.equal(el(manifestOf(h), 'claude-2', 'CLAUDE.md').kind, 'symlink');
    assert.equal(fs.statSync(P).nlink, 2, 'the old hardlink now lives in the backup');
  } else {
    // The OS refuses symbolic links: the hardlink is made again, and that is reported.
    assert.equal(apply.json.done.find((d) => d.element === 'CLAUDE.md').kind, 'hardlink');
    assert.equal(el(manifestOf(h), 'claude-2', 'CLAUDE.md').kind, 'hardlink');
  }
  assert.equal(acc(h.home, ['check']).json.status, 'ok');
  const undo = acc(h.home, ['undo', '--stamp', apply.json.stamp, '--yes']);
  assert.equal(undo.code, 0, undo.stdout);
  assert.ok(!isLink(S) && resolvesTo(S, P), 'undo did not bring the hardlink back');
  assert.equal(fs.statSync(S).nlink, 2);
  assert.equal(el(manifestOf(h), 'claude-2', 'CLAUDE.md').kind, 'hardlink');
});

