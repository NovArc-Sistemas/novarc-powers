test('apply: a failed step is reported and rolled back, the others still run, and the exit code says so', (t) => {
  const h = buildHome({ codex: false, agents: false });
  t.after(() => rmrf(h.root));
  const planFile = path.join(h.root, 'plan.json');
  acc(h.home, ['plan', '--primary', 'claude-1', '--out', planFile]);
  // The app holds its state file: the MCP step must give up without touching it.
  fs.mkdirSync(`${h.state2}.lock`);
  const before = read(h.state2);
  const r = acc(h.home, ['apply', '--plan', planFile, '--yes']);
  assert.equal(r.code, 1);
  assert.equal(r.json.ok, false);
  assert.equal(r.json.failed, 1);
  const failed = r.json.done.find((d) => d.result === 'failed');
  assert.deepEqual([failed.account, failed.element], ['claude-2', 'mcp servers']);
  assert.match(failed.error, /writing its state file right now/);
  assert.equal(read(h.state2), before);
  assert.ok(r.json.done.filter((d) => d.result === 'done').length >= 5, 'the other steps were carried out');
  assert.ok(resolvesTo(path.join(h.acc, 'settings.json'), path.join(h.claude, 'settings.json')));
  assert.ok(!manifestOf(h).accounts[0].elements.some((e) => e.name.startsWith('mcp servers/')), 'a failed step records nothing');
  // Once the lock is gone, a fresh plan finishes the job.
  fs.rmdirSync(`${h.state2}.lock`);
  const again = planAndApply(h, 'claude-1');
  assert.equal(again.apply.code, 0, again.apply.stdout);
  assert.ok(JSON.parse(read(h.state2)).mcpServers.remote);
});

