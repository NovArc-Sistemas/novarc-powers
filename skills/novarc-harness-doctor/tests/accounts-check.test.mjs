test('check: the script is one self-contained file that runs from anywhere', (t) => {
  const source = read(path.join(SCRIPTS, 'sync-check.mjs'));
  const imports = [...source.matchAll(/^\s*import\s[^'"]*['"]([^'"]+)['"]/gm)].map((m) => m[1]);
  assert.ok(imports.length >= 4);
  assert.ok(imports.every((s) => s.startsWith('node:')), `imports outside node: ${imports.filter((s) => !s.startsWith('node:'))}`);
  assert.ok(!/\bimport\s*\(/.test(source) && !/\brequire\s*\(/.test(source), 'no dynamic loading either');
  // Copied alone next to a manifest, it uses that manifest even when home points elsewhere.
  const h = synced(t);
  const copy = path.join(h.sync, 'sync-check.mjs');
  fs.copyFileSync(path.join(SCRIPTS, 'sync-check.mjs'), copy);
  fs.rmSync(path.join(h.acc, 'keybindings.json'));
  const elsewhere = path.join(h.root, 'another-home');
  fs.mkdirSync(elsewhere);
  const r = check(elsewhere, ['--repair'], { script: copy });
  assert.equal(r.code, 0);
  assert.match(r.stdout, /repaired 1 \(claude-2 keybindings\.json\)/);
  assert.ok(resolvesTo(path.join(h.acc, 'keybindings.json'), path.join(h.claude, 'keybindings.json')));
  const j = check(elsewhere, ['--json'], { script: copy });
  assert.equal(JSON.parse(j.stdout).status, 'ok');
});

test('check: fast enough for a session-start hook', (t) => {
  const h = synced(t);
  const times = [];
  for (let i = 0; i < 7; i++) {
    const s = process.hrtime.bigint();
    const report = runCheck({ repair: true, home: h.home });
    times.push(Number(process.hrtime.bigint() - s) / 1e6);
    assert.equal(report.status, 'ok');
  }
  times.sort((a, b) => a - b);
  // The work itself, without the cost of starting node. Generous: CI machines are slow.
  assert.ok(times[3] < 500, `median ${times[3].toFixed(1)} ms over ${times.length} runs`);
  t.diagnostic(`runCheck over 21 elements: min ${times[0].toFixed(1)} ms, median ${times[3].toFixed(1)} ms`);
});
