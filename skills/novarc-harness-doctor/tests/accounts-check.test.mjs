  fs.writeFileSync(h.state1, JSON.stringify(s, null, 2));
  assert.match(check(h.home, ['--repair']).stdout, /repaired 1 \(codex-1 mcp servers\/context7\)/);
  const now = read(toml);
  assert.ok(now.includes('MODE = "slow"'));
