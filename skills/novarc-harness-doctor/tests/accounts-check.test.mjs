/** A fake home with every account synced from claude-1. */
function synced(t, { extra = {}, args = ALL, home = {} } = {}) {
  const h = buildHome(home);
  t.after(() => rmrf(h.root));
  const r = planAndApply(h, 'claude-1', args, extra);
  assert.equal(r.apply.code, 0, r.apply.stdout + r.apply.stderr);
  return h;
}
const elementOf = (report, id, name) => report.accounts.find((a) => a.id === id).elements.find((e) => e.name === name);

