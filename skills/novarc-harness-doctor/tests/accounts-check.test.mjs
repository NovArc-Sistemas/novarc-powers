test('check: a hardlink broken by an atomic save is re-created only when nobody edited the copy', (t) => {
  const h = synced(t, { extra: HARD });
  const P = path.join(h.claude, 'settings.json');
  const S = path.join(h.acc, 'settings.json');
  const manifest = () => json(path.join(h.sync, 'manifest.json')).accounts[0].elements.find((e) => e.name === 'settings.json');
  assert.equal(manifest().kind, 'hardlink');
  assert.ok(resolvesTo(S, P));

  // 1. An editor saves the SECONDARY atomically with the same bytes: the link is gone, the
  //    content is not. Safe to link again.
  atomicSave(S, fs.readFileSync(S));
  assert.ok(!resolvesTo(S, P), 'the simulated atomic save did not break the hardlink');
  assert.match(check(h.home, [], { extra: HARD }).stdout, /needs attention 1 \(claude-2 settings\.json: the link became a separate identical copy/);
  assert.match(check(h.home, ['--repair'], { extra: HARD }).stdout, /repaired 1 \(claude-2 settings\.json\)/);
  assert.ok(resolvesTo(S, P));
  assert.equal(fs.statSync(S).nlink, 2);

  // 2. The PRIMARY is saved atomically with new content: the secondary still holds the last
  //    known bytes, so nobody edited it. Link again; it now shows the new content.
  const next = read(P).replace('"model": "x"', '"model": "y"');
  atomicSave(P, next);
  assert.ok(!resolvesTo(S, P));
  assert.notEqual(read(S), next);
  assert.match(check(h.home, ['--repair'], { extra: HARD }).stdout, /repaired 1 \(claude-2 settings\.json\)/);
  assert.ok(resolvesTo(S, P));
  assert.equal(read(S), next);
  assert.equal(manifest().contentHash, sha(P));

  // 3. The secondary is saved atomically with DIFFERENT content: a hand edit. Reported, kept.
  const mine = read(S).replace('"model": "y"', '"model": "edited-in-the-second-account"');
  atomicSave(S, mine);
  for (let i = 0; i < 2; i++) {
    const r = check(h.home, ['--repair'], { extra: HARD });
    assert.match(r.stdout, /needs attention 1 \(claude-2 settings\.json: edited by hand; not overwritten \(~\/\.hostapp\/[^ ]*\/settings\.json vs ~\/\.claude\/settings\.json\)\)/);
  }
  assert.equal(read(S), mine, 'a hand-edited secondary was overwritten');
  assert.equal(read(P), next);
  assert.ok(!resolvesTo(S, P));

  // 4. An in-place edit through an intact hardlink is simply shared, and remembered.
  const h2 = synced(t, { extra: HARD });
  const P2 = path.join(h2.claude, 'keybindings.json');
  const S2 = path.join(h2.acc, 'keybindings.json');
  fs.writeFileSync(P2, '{"bindings": ["in place"]}\n');
  assert.equal(read(S2), '{"bindings": ["in place"]}\n');
  assert.equal(check(h2.home, ['--repair'], { extra: HARD }).stdout, '');
  atomicSave(P2, '{"bindings": ["then atomically"]}\n');
  assert.match(check(h2.home, ['--repair'], { extra: HARD }).stdout, /repaired 1 \(claude-2 keybindings\.json\)/);
  assert.equal(read(S2), '{"bindings": ["then atomically"]}\n');
});

test('check: a symbolic link replaced by a real file follows the same rule', (t) => {
  const h = synced(t);
  const P = path.join(h.claude, 'keybindings.json');
  const S = path.join(h.acc, 'keybindings.json');
  // Identical copy where the link was: safe to link again.
  fs.rmSync(S);
  fs.copyFileSync(P, S);
  assert.match(check(h.home, ['--repair']).stdout, /repaired 1 \(claude-2 keybindings\.json\)/);
  assert.ok(resolvesTo(S, P));
  // A different file where the link was: left alone.
  fs.rmSync(S);
  fs.writeFileSync(S, '{"bindings": ["typed here"]}\n');
  assert.match(check(h.home, ['--repair']).stdout, /claude-2 keybindings\.json: edited by hand; not overwritten/);
  assert.equal(read(S), '{"bindings": ["typed here"]}\n');
  // A real folder where a linked folder was: reported, never removed.
  const dir = path.join(h.acc, 'commands');
  dropLink(dir);
  write(path.join(dir, 'mine.md'), 'mine\n');
  const r = check(h.home, ['--repair']);
  assert.match(r.stdout, /commands\/: a real folder or file replaced the link/);
  assert.equal(read(path.join(dir, 'mine.md')), 'mine\n');
  // A link somebody pointed elsewhere is theirs.
  const rules = path.join(h.acc, 'rules');
  dropLink(rules);
  fs.symlinkSync(path.join(h.claude, 'agents'), rules, 'junction');
  assert.match(check(h.home, ['--repair']).stdout, /rules\/: the link points somewhere else/);
  assert.ok(resolvesTo(rules, path.join(h.claude, 'agents')));
});

