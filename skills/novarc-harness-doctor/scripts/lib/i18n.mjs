export const STRINGS = { en, pt };

/** `state.language`, else the --lang flag, else English. Anything unsupported falls back to English. */
export function resolveLanguage(stateLanguage, flagLanguage) {
  if (LANGUAGES.includes(stateLanguage)) return stateLanguage;
  if (LANGUAGES.includes(flagLanguage)) return flagLanguage;
  return DEFAULT_LANGUAGE;
}

/** Replace {key} placeholders. Unknown keys are left as written. */
export function fill(template, vars = {}) {
  return String(template).replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
}

/** Pick the `one` or `other` form for a count and fill `{n}` plus any other placeholder. */
export function plural(forms, n, vars = {}) {
  const tpl = forms && typeof forms === 'object' ? (n === 1 ? forms.one : forms.other) : forms;
  return fill(tpl, { n, ...vars });
}

/** Label for an enum value from one of the dictionary maps; the raw value when no label exists. */
export function label(map, value) {
  return map && Object.prototype.hasOwnProperty.call(map, value) ? map[value] : String(value ?? '');
}

/**
 * Token count as people read it: 61.2M, 4.1k (en) or 61,2 mi, 4,1 mil (pt). Floors to one
 * decimal so a number shown is never larger than the one measured.
 */
export function compactTokens(n, lang) {
  if (typeof n !== 'number' || !Number.isFinite(n)) return '-';
  const u = STRINGS[lang].tokenUnits;
  const fmt = (v, unit) => (Math.floor(v * 10 + 1e-7) / 10).toLocaleString(LOCALES[lang], { maximumFractionDigits: 1 }) + unit;
  const abs = Math.abs(n);
  if (abs >= 1e9) return fmt(n / 1e9, u.b);
  if (abs >= 1e6) return fmt(n / 1e6, u.m);
  if (abs >= 1e3) return fmt(n / 1e3, u.k);
  return String(Math.round(n));
}
